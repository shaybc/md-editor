(function(global) {
  "use strict";

  /** Creates deterministic runnable Python project manifests. */
  function registerMarkdownViewerNewProjectPythonGenerator(app) {
    function file(path, content) {
      return { path, content: String(content).replace(/\r?\n/g, "\n") };
    }

    /** Return all Python-specific files and common documentation metadata. */
    function createManifest(specification) {
      const packageRoot = specification.packageLayout === "src" ? `src/${specification.packageName}` : specification.packageName;
      const entryFile = `${packageRoot}/${specification.entryScript}`;
      const files = [
        file(`${packageRoot}/__init__.py`, `"""${specification.projectName} package."""\n`),
        file(entryFile, `"""Application entry point generated by MD-Editor."""\n\n\ndef main() -> None:\n    """Print a greeting."""\n    print("Hello, world!")\n\n\nif __name__ == "__main__":\n    main()\n`)
      ];
      if (specification.dependencyFormat === "pyproject") {
        files.push(file("pyproject.toml", `[project]\nname = "${specification.projectName.toLowerCase().replace(/[^a-z0-9-]+/g, "-")}"\nversion = "0.1.0"\nrequires-python = ">=${specification.pythonVersion}"\ndependencies = []\n`));
      } else {
        files.push(file("requirements.txt", "# Add one pinned dependency per line.\n"));
      }
      const runCommand = `${specification.interpreter} ${entryFile}`;
      const installCommand = specification.dependencyFormat === "pyproject"
        ? `${specification.interpreter} -m pip install -e .`
        : `${specification.interpreter} -m pip install -r requirements.txt`;
      return {
        files,
        copyDirectories: [],
        entryFile,
        sourceFolders: [specification.packageLayout === "src" ? "src" : specification.packageName],
        testFolders: ["tests"],
        runtime: { command: specification.interpreter, version: specification.pythonVersion },
        settings: {
          packageLayout: specification.packageLayout,
          packageName: specification.packageName,
          dependencyFormat: specification.dependencyFormat,
          virtualEnvironment: specification.virtualEnvironment
        },
        prerequisites: `Python ${specification.pythonVersion}`,
        setupCommands: [
          `${specification.interpreter} -m venv ${specification.virtualEnvironment}`,
          `# Windows PowerShell: ${specification.virtualEnvironment}\\Scripts\\Activate.ps1`,
          `# macOS/Linux: source ${specification.virtualEnvironment}/bin/activate`,
          installCommand
        ],
        buildCommand: `${specification.interpreter} -m compileall ${specification.packageLayout === "src" ? "src" : specification.packageName}`,
        runCommand,
        ignore: ["__pycache__/", "*.py[cod]", specification.virtualEnvironment + "/", ".pytest_cache/", "dist/", "build/", "*.egg-info/"],
        agentRules: [
          `Use Python ${specification.pythonVersion} through \`${specification.interpreter}\`.`,
          `Keep application code under \`${packageRoot}\` and tests under \`tests\`.`,
          `Validate changes with \`${specification.interpreter} -m compileall ${specification.packageLayout === "src" ? "src" : specification.packageName}\`.`
        ]
      };
    }

    const api = { createManifest };
    app?.registerModule?.("newProjectPythonGenerator", api);
    return api;
  }

  global.registerMarkdownViewerNewProjectPythonGenerator = registerMarkdownViewerNewProjectPythonGenerator;
})(typeof window !== "undefined" ? window : globalThis);
