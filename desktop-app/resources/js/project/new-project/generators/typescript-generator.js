(function(global) {
  "use strict";

  /** Creates deterministic runnable TypeScript project manifests. */
  function registerMarkdownViewerNewProjectTypeScriptGenerator(app) {
    function file(path, content) {
      return { path, content: String(content).replace(/\r?\n/g, "\n") };
    }

    /** Return all TypeScript-specific files and common documentation metadata. */
    function createManifest(specification) {
      const relativeEntry = specification.entryScript.toLowerCase().startsWith(`${specification.sourceFolder.toLowerCase()}/`)
        ? specification.entryScript.slice(specification.sourceFolder.length + 1)
        : specification.entryScript;
      const compiledEntry = `${specification.outputFolder}/${relativeEntry.replace(/\.ts$/i, ".js")}`;
      const packageJson = {
        name: specification.packageName,
        version: specification.packageVersion,
        private: true,
        type: specification.moduleSystem,
        scripts: { build: "tsc", start: `node ${compiledEntry}`, check: "tsc --noEmit" },
        devDependencies: { typescript: "^5.9.0" },
        packageManager: `${specification.packageManager}@${specification.packageManagerVersion}`
      };
      const effectiveModule = specification.moduleResolution === "NodeNext"
        ? "NodeNext"
        : (specification.moduleResolution === "Bundler" ? "ESNext" : (specification.moduleSystem === "commonjs" ? "CommonJS" : "ESNext"));
      const tsconfig = {
        compilerOptions: {
          target: specification.ecmaTarget,
          module: effectiveModule,
          moduleResolution: specification.moduleResolution,
          rootDir: specification.sourceFolder,
          outDir: specification.outputFolder,
          strict: specification.strict,
          sourceMap: specification.sourceMaps,
          declaration: specification.declarations,
          esModuleInterop: true,
          forceConsistentCasingInFileNames: true,
          skipLibCheck: true
        },
        include: [`${specification.sourceFolder}/**/*.ts`]
      };
      return {
        files: [
          file("package.json", JSON.stringify(packageJson, null, 2) + "\n"),
          file(".nvmrc", specification.nodeVersion + "\n"),
          file("tsconfig.json", JSON.stringify(tsconfig, null, 2) + "\n"),
          file(specification.entryScript, `/** Application entry point generated by MD-Editor. */\nfunction main(): void {\n  console.log("Hello, world!");\n}\n\nmain();\n`)
        ],
        copyDirectories: [],
        entryFile: specification.entryScript,
        sourceFolders: [specification.sourceFolder],
        testFolders: ["test"],
        runtime: { name: "Node.js", version: specification.nodeVersion },
        settings: {
          packageManager: specification.packageManager,
          packageManagerVersion: specification.packageManagerVersion,
          moduleSystem: specification.moduleSystem,
          target: specification.ecmaTarget,
          module: effectiveModule,
          moduleResolution: specification.moduleResolution,
          outputFolder: specification.outputFolder
        },
        prerequisites: `Node.js ${specification.nodeVersion}, ${specification.packageManager} ${specification.packageManagerVersion}, and TypeScript`,
        setupCommands: [`${specification.packageManager} install`],
        buildCommand: `${specification.packageManager} run build`,
        runCommand: `${specification.packageManager} start`,
        ignore: ["node_modules/", specification.outputFolder + "/", "coverage/", "*.log", ".env", ".env.*"],
        agentRules: [
          `Use Node.js ${specification.nodeVersion}, TypeScript, and ${specification.packageManager} ${specification.packageManagerVersion}.`,
          `Keep TypeScript sources under \`${specification.sourceFolder}\` and generated JavaScript under \`${specification.outputFolder}\`.`,
          `Validate changes with \`${specification.packageManager} run check\`.`
        ]
      };
    }

    const api = { createManifest };
    app?.registerModule?.("newProjectTypeScriptGenerator", api);
    return api;
  }

  global.registerMarkdownViewerNewProjectTypeScriptGenerator = registerMarkdownViewerNewProjectTypeScriptGenerator;
})(typeof window !== "undefined" ? window : globalThis);
