(function(global) {
  "use strict";

  /** Creates deterministic runnable C# console project manifests. */
  function registerMarkdownViewerNewProjectCSharpGenerator(app) {
    function file(path, content) {
      return { path, content: String(content).replace(/\r?\n/g, "\n") };
    }

    /** Return all C#-specific files and common documentation metadata. */
    function createManifest(specification) {
      const projectFile = `${specification.projectName}.csproj`;
      const entryFile = `${specification.entryClass}.cs`;
      return {
        files: [
          file(projectFile, `<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>${specification.targetFramework}</TargetFramework>
    <RootNamespace>${specification.rootNamespace}</RootNamespace>
    <ImplicitUsings>${specification.implicitUsings ? "enable" : "disable"}</ImplicitUsings>
    <Nullable>${specification.nullable ? "enable" : "disable"}</Nullable>
  </PropertyGroup>
</Project>
`),
          file(entryFile, `using System;

namespace ${specification.rootNamespace};

/// <summary>Application entry point generated by MD-Editor.</summary>
internal static class ${specification.entryClass}
{
    /// <summary>Prints a greeting.</summary>
    private static void Main()
    {
        Console.WriteLine("Hello, world!");
    }
}
`)
        ],
        copyDirectories: [],
        entryFile,
        sourceFolders: ["."],
        testFolders: ["tests"],
        runtime: { name: ".NET SDK", version: specification.dotnetSdkVersion, targetFramework: specification.targetFramework },
        settings: {
          projectFile,
          rootNamespace: specification.rootNamespace,
          nullable: specification.nullable,
          implicitUsings: specification.implicitUsings
        },
        prerequisites: `.NET SDK ${specification.dotnetSdkVersion}`,
        setupCommands: ["dotnet restore"],
        buildCommand: "dotnet build",
        runCommand: "dotnet run",
        ignore: ["bin/", "obj/", "*.user", "*.suo", ".vs/", "TestResults/"],
        agentRules: [
          `Use .NET SDK ${specification.dotnetSdkVersion} and target \`${specification.targetFramework}\`.`,
          `Keep the console entry point in \`${entryFile}\`.`,
          "Validate changes with `dotnet build`."
        ]
      };
    }

    const api = { createManifest };
    app?.registerModule?.("newProjectCSharpGenerator", api);
    return api;
  }

  global.registerMarkdownViewerNewProjectCSharpGenerator = registerMarkdownViewerNewProjectCSharpGenerator;
})(typeof window !== "undefined" ? window : globalThis);
