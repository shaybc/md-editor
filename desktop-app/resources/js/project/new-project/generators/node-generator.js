(function(global) {
  "use strict";

  /** Creates deterministic runnable JavaScript and Node.js project manifests. */
  function registerMarkdownViewerNewProjectNodeGenerator(app) {
    function file(path, content) {
      return { path, content: String(content).replace(/\r?\n/g, "\n") };
    }

    /** Return all Node.js-specific files and common documentation metadata. */
    function createManifest(specification) {
      const packageJson = {
        name: specification.packageName,
        version: specification.packageVersion,
        private: true,
        type: specification.moduleSystem,
        main: specification.entryScript,
        scripts: { start: `node ${specification.entryScript}`, check: `node --check ${specification.entryScript}` },
        packageManager: `${specification.packageManager}@${specification.packageManagerVersion}`
      };
      return {
        files: [
          file("package.json", JSON.stringify(packageJson, null, 2) + "\n"),
          file(".nvmrc", specification.nodeVersion + "\n"),
          file(specification.entryScript, `/** Application entry point generated by MD-Editor. */\nfunction main() {\n  console.log("Hello, world!");\n}\n\nmain();\n`)
        ],
        copyDirectories: [],
        entryFile: specification.entryScript,
        sourceFolders: [specification.entryScript.split("/").slice(0, -1).join("/") || "."],
        testFolders: ["test"],
        runtime: { name: "Node.js", version: specification.nodeVersion },
        settings: {
          packageManager: specification.packageManager,
          packageManagerVersion: specification.packageManagerVersion,
          moduleSystem: specification.moduleSystem,
          packageName: specification.packageName
        },
        prerequisites: `Node.js ${specification.nodeVersion} and ${specification.packageManager} ${specification.packageManagerVersion}`,
        buildCommand: `${specification.packageManager} run check`,
        runCommand: `${specification.packageManager} start`,
        ignore: ["node_modules/", "dist/", "coverage/", "*.log", ".env", ".env.*"],
        agentRules: [
          `Use Node.js ${specification.nodeVersion} and ${specification.packageManager} ${specification.packageManagerVersion}.`,
          `Keep the runnable entry point at \`${specification.entryScript}\`.`,
          `Validate changes with \`${specification.packageManager} run check\`.`
        ]
      };
    }

    const api = { createManifest };
    app?.registerModule?.("newProjectNodeGenerator", api);
    return api;
  }

  global.registerMarkdownViewerNewProjectNodeGenerator = registerMarkdownViewerNewProjectNodeGenerator;
})(typeof window !== "undefined" ? window : globalThis);
