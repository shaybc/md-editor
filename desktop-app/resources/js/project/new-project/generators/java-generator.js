(function(global) {
  "use strict";

  /** Creates deterministic runnable Java project manifests for javac, Maven, and Gradle. */
  function registerMarkdownViewerNewProjectJavaGenerator(app) {
    function file(path, content) {
      return { path, content: String(content).replace(/\r?\n/g, "\n") };
    }

    function packagePath(specification) {
      return specification.packageName.replace(/\./g, "/");
    }

    function dependencyParts(entry) {
      const [group, artifact, version, scope = "implementation"] = entry.split(":");
      return { group, artifact, version, scope };
    }

    function createMainSource(specification) {
      return `package ${specification.packageName};

/**
 * Application entry point generated by MD-Editor.
 */
public final class ${specification.mainClass} {
    private ${specification.mainClass}() {
    }

    /**
     * Prints a greeting.
     *
     * @param args command-line arguments; unused
     */
    public static void main(String[] args) {
        System.out.println("Hello, world!");
    }
}
`;
    }

    function createPom(specification, jdkVersion) {
      const dependencies = specification.dependencies.map((entry) => {
        const dependency = dependencyParts(entry);
        const mavenScopes = {
          compile: "compile",
          implementation: "compile",
          runtime: "runtime",
          runtimeOnly: "runtime",
          provided: "provided",
          compileOnly: "provided",
          test: "test",
          testImplementation: "test"
        };
        const mavenScope = mavenScopes[dependency.scope] || "compile";
        const scope = mavenScope === "compile" ? "" : `\n      <scope>${mavenScope}</scope>`;
        return `    <dependency>
      <groupId>${dependency.group}</groupId>
      <artifactId>${dependency.artifact}</artifactId>
      <version>${dependency.version}</version>${scope}
    </dependency>`;
      }).join("\n");
      return `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>${specification.groupId}</groupId>
  <artifactId>${specification.artifactId}</artifactId>
  <version>${specification.version}</version>
  <properties>
    <maven.compiler.release>${jdkVersion}</maven.compiler.release>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
  </properties>
  <dependencies>
${dependencies}
  </dependencies>
  <build>
    <sourceDirectory>${specification.sourceFolder}</sourceDirectory>
    <testSourceDirectory>${specification.testFolder}</testSourceDirectory>
    <plugins>
      <plugin>
        <groupId>org.codehaus.mojo</groupId>
        <artifactId>exec-maven-plugin</artifactId>
        <version>3.5.0</version>
        <configuration><mainClass>${specification.packageName}.${specification.mainClass}</mainClass></configuration>
      </plugin>
    </plugins>
  </build>
</project>
`;
    }

    function gradleDependency(entry, kotlin) {
      const dependency = dependencyParts(entry);
      const configurations = {
        compile: "implementation",
        implementation: "implementation",
        runtime: "runtimeOnly",
        runtimeOnly: "runtimeOnly",
        provided: "compileOnly",
        compileOnly: "compileOnly",
        test: "testImplementation",
        testImplementation: "testImplementation"
      };
      const configuration = configurations[dependency.scope] || dependency.scope;
      const coordinate = `${dependency.group}:${dependency.artifact}:${dependency.version}`;
      return kotlin ? `    ${configuration}("${coordinate}")` : `    ${configuration} '${coordinate}'`;
    }

    function createGradleBuild(specification, jdkVersion) {
      const kotlin = specification.gradleDsl === "kotlin";
      const dependencies = specification.dependencies.map((entry) => gradleDependency(entry, kotlin)).join("\n");
      if (kotlin) {
        return `plugins {
    application
    java
}

group = "${specification.groupId}"
version = "${specification.version}"

java {
    toolchain { languageVersion.set(JavaLanguageVersion.of(${jdkVersion})) }
}

repositories { mavenCentral() }

sourceSets {
    main { java.setSrcDirs(listOf("${specification.sourceFolder}")) }
    test { java.setSrcDirs(listOf("${specification.testFolder}")) }
}

dependencies {
${dependencies}
}

application {
    mainClass.set("${specification.packageName}.${specification.mainClass}")
}
`;
      }
      return `plugins {
    id 'application'
    id 'java'
}

group = '${specification.groupId}'
version = '${specification.version}'

java {
    toolchain { languageVersion = JavaLanguageVersion.of(${jdkVersion}) }
}

repositories { mavenCentral() }

sourceSets {
    main.java.srcDirs = ['${specification.sourceFolder}']
    test.java.srcDirs = ['${specification.testFolder}']
}

dependencies {
${dependencies}
}

application {
    mainClass = '${specification.packageName}.${specification.mainClass}'
}
`;
    }

    function createBuildPath(specification) {
      return {
        schemaVersion: 10,
        type: "md-editor-java-build-path",
        projectJdkId: specification.projectJdkId,
        buildSystem: specification.projectType === "standard" ? "javac" : specification.projectType,
        sourceFolders: [specification.sourceFolder, specification.testFolder],
        classpathFolders: specification.projectType === "standard" ? specification.classpathFolders : [],
        jarFiles: specification.projectType === "standard" ? specification.jarFiles : [],
        javacProfile: specification.projectType === "standard" ? {
          sourceFolders: [specification.sourceFolder, specification.testFolder],
          classpathEntries: specification.classpathFolders.concat(specification.jarFiles),
          outputMode: "classes",
          outputPath: specification.outputFolder,
          exportSources: false
        } : null,
        analysisScope: { mode: "all", inventoryKind: "", deselectedEntryIds: [], customized: false },
        maven: { compileTests: true, runTests: false },
        gradle: {
          mode: specification.gradleInstallationId === "built-in" ? "built-in" : "installation",
          installationId: specification.gradleInstallationId === "built-in" ? null : specification.gradleInstallationId,
          compileTests: true,
          runTests: false
        }
      };
    }

    /** Return all Java-specific files and common documentation metadata. */
    function createManifest(specification) {
      const jdkVersion = Number(specification.projectJdkFeature) || 21;
      const mainPath = `${specification.sourceFolder}/${packagePath(specification)}/${specification.mainClass}.java`;
      const files = [
        file(mainPath, createMainSource(specification)),
        file(".md-editor/java-build-path.json", JSON.stringify(createBuildPath(specification), null, 2) + "\n")
      ];
      let buildCommand;
      let runCommand;
      if (specification.projectType === "maven") {
        files.push(file("pom.xml", createPom(specification, jdkVersion)));
        buildCommand = "mvn clean package";
        runCommand = "mvn exec:java";
      } else if (specification.projectType === "gradle") {
        const kotlin = specification.gradleDsl === "kotlin";
        files.push(file(kotlin ? "settings.gradle.kts" : "settings.gradle", kotlin
          ? `rootProject.name = "${specification.artifactId}"\n`
          : `rootProject.name = '${specification.artifactId}'\n`));
        files.push(file(kotlin ? "build.gradle.kts" : "build.gradle", createGradleBuild(specification, jdkVersion)));
        buildCommand = "gradle build";
        runCommand = "gradle run";
      } else {
        const classpath = specification.classpathFolders.concat(specification.jarFiles);
        const separator = global.NL_OS === "Windows" ? ";" : ":";
        const classpathArgument = classpath.length ? ` -cp "${classpath.join(separator)}"` : "";
        buildCommand = `javac${classpathArgument} -d ${specification.outputFolder} ${mainPath}`;
        runCommand = `java -cp ${specification.outputFolder} ${specification.packageName}.${specification.mainClass}`;
      }
      if (specification.eclipseSettingsEnabled) {
        files.push(file(".md-editor/eclipse-preferences.json", JSON.stringify({ setting: "existing" }, null, 2) + "\n"));
      }
      return {
        files,
        copyDirectories: specification.eclipseSettingsEnabled
          ? [{ source: specification.eclipseSettingsSource, target: ".settings" }]
          : [],
        entryFile: mainPath,
        sourceFolders: [specification.sourceFolder],
        testFolders: [specification.testFolder],
        runtime: { id: specification.projectJdkId, version: String(jdkVersion), name: specification.projectJdkName || `JDK ${jdkVersion}` },
        settings: {
          buildSystem: specification.projectType === "standard" ? "javac" : specification.projectType,
          groupId: specification.groupId,
          artifactId: specification.artifactId,
          version: specification.version,
          packageName: specification.packageName,
          mainClass: specification.mainClass,
          gradleDsl: specification.projectType === "gradle" ? specification.gradleDsl : null,
          gradleInstallationId: specification.projectType === "gradle" ? specification.gradleInstallationId : null,
          gradleVersion: specification.projectType === "gradle" ? specification.gradleVersion || null : null
        },
        prerequisites: `JDK ${jdkVersion}${specification.projectType === "maven" ? " and Maven" : specification.projectType === "gradle" ? " and the selected Gradle installation" : ""}`,
        buildCommand,
        runCommand,
        ignore: [".gradle/", "build/", "target/", "bin/", "out/", "*.class", "*.jar", ".classpath", ".project"],
        agentRules: [
          `Use JDK ${jdkVersion} and the ${specification.projectType === "standard" ? "standard javac" : specification.projectType} project layout.`,
          `Keep production sources under \`${specification.sourceFolder}\` and tests under \`${specification.testFolder}\`.`,
          `Validate changes with \`${buildCommand}\`.`
        ]
      };
    }

    const api = { createManifest };
    app?.registerModule?.("newProjectJavaGenerator", api);
    return api;
  }

  global.registerMarkdownViewerNewProjectJavaGenerator = registerMarkdownViewerNewProjectJavaGenerator;
})(typeof window !== "undefined" ? window : globalThis);
