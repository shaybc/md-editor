(function(global) {
  "use strict";

  /** Owns New Project manifest preparation, guarded filesystem writes, Git initialization, and rollback. */
  function registerMarkdownViewerProjectScaffolder(app, deps = {}) {
    const Neutralino = deps.Neutralino || global.Neutralino;
    const specificationApi = deps.specification;

    function normalizePath(value) {
      return String(value || "").replace(/\\/g, "/").replace(/\/+$/, "");
    }

    function joinPath(parent, child) {
      return `${normalizePath(parent)}/${String(child || "").replace(/\\/g, "/").replace(/^\/+/, "")}`;
    }

    function parentPath(path) {
      const normalized = normalizePath(path);
      const separatorIndex = normalized.lastIndexOf("/");
      return separatorIndex > 0 ? normalized.slice(0, separatorIndex) : "";
    }

    async function getStats(path) {
      try {
        return await Neutralino.filesystem.getStats(path);
      } catch (_error) {
        return null;
      }
    }

    async function listDirectory(path) {
      return (await Neutralino.filesystem.readDirectory(path))
        .filter((entry) => entry.entry !== "." && entry.entry !== "..");
    }

    function commonReadme(specification, generated) {
      const setup = Array.isArray(generated.setupCommands) && generated.setupCommands.length
        ? `## Setup\n\n\`\`\`text\n${generated.setupCommands.join("\n")}\n\`\`\`\n\n`
        : "";
      return `# ${specification.projectName}

Runnable ${specification.language} project generated by MD-Editor.

## Prerequisites

${generated.prerequisites}

## Project layout

- Entry point: \`${generated.entryFile}\`
- Source folders: ${generated.sourceFolders.map((path) => `\`${path}\``).join(", ")}
- Test folders: ${generated.testFolders.map((path) => `\`${path}\``).join(", ")}

${setup}## Build

\`\`\`text
${generated.buildCommand}
\`\`\`

## Run

\`\`\`text
${generated.runCommand}
\`\`\`

Generated files do not install dependencies or create tool wrappers. Install the prerequisites before running these commands.
`;
    }

    function commonAgents(specification, generated) {
      return `# AGENTS.md

## Project rules

${generated.agentRules.map((rule) => `- ${rule}`).join("\n")}
- Keep generated and dependency folders out of version control.
- Do not change runtime or build-tool versions without updating \`README.md\` and \`.md-editor/project.json\`.
- Make minimal, scoped changes and preserve unrelated behavior.

## Commands

- Build/validate: \`${generated.buildCommand}\`
- Run: \`${generated.runCommand}\`
`;
    }

    function addCommonFiles(specification, generated) {
      const settings = specificationApi.toProjectSettings(specification, generated);
      return generated.files.concat([
        { path: "README.md", content: commonReadme(specification, generated) },
        { path: "AGENTS.md", content: commonAgents(specification, generated) },
        { path: ".gitignore", content: Array.from(new Set(generated.ignore)).join("\n") + "\n" },
        { path: ".md-editor/project.json", content: JSON.stringify(settings, null, 2) + "\n" }
      ]);
    }

    async function enumerateCopyDirectory(sourceRoot, targetRoot) {
      const sourceStats = await getStats(sourceRoot);
      if (!sourceStats?.isDirectory) throw new Error(`Copy source directory was not found: ${sourceRoot}`);
      const files = [];
      const directories = [targetRoot];
      async function visit(source, target) {
        for (const entry of await listDirectory(source)) {
          const sourcePath = joinPath(source, entry.entry);
          const targetPath = joinPath(target, entry.entry);
          if (entry.type === "DIRECTORY") {
            directories.push(targetPath);
            await visit(sourcePath, targetPath);
          } else if (entry.type === "FILE") {
            files.push({ path: targetPath, copyFrom: sourcePath });
          }
        }
      }
      await visit(sourceRoot, targetRoot);
      return { files, directories };
    }

    function validateManifest(files, directories) {
      const seen = new Set();
      for (const entry of files) {
        if (!specificationApi.isSafeRelativePath(entry.path)) throw new Error(`Generated path is unsafe: ${entry.path}`);
        const key = normalizePath(entry.path).toLowerCase();
        if (seen.has(key)) throw new Error(`Generated file collision: ${entry.path}`);
        seen.add(key);
      }
      for (const directory of directories) {
        if (directory === ".") continue;
        if (!specificationApi.isSafeRelativePath(directory)) throw new Error(`Generated directory is unsafe: ${directory}`);
        if (seen.has(normalizePath(directory).toLowerCase())) throw new Error(`Generated file and directory collide: ${directory}`);
      }
    }

    function expandDirectoryAncestors(directories) {
      const expanded = [];
      for (const directory of directories) {
        let current = "";
        for (const segment of normalizePath(directory).split("/").filter(Boolean)) {
          current = current ? `${current}/${segment}` : segment;
          expanded.push(current);
        }
      }
      return expanded;
    }

    /**
     * Build the complete previewable manifest, including copied Eclipse preference files.
     * This performs read-only source inspection and writes nothing.
     */
    async function prepare(specification, generated) {
      const files = addCommonFiles(specification, generated);
      const directories = [".md-editor"].concat(generated.sourceFolders, generated.testFolders);
      for (const copy of generated.copyDirectories || []) {
        const copied = await enumerateCopyDirectory(copy.source, copy.target);
        files.push(...copied.files);
        directories.push(...copied.directories);
      }
      files.forEach((entry) => {
        const parent = parentPath(entry.path);
        if (parent) directories.push(parent);
      });
      const uniqueDirectories = Array.from(new Set(expandDirectoryAncestors(directories).filter((path) => path && path !== ".")));
      validateManifest(files, uniqueDirectories);
      return { files, directories: uniqueDirectories.sort((a, b) => a.split("/").length - b.split("/").length), generated };
    }

    async function preflight(specification, prepared) {
      const parentStats = await getStats(specification.parentDirectory);
      if (!parentStats?.isDirectory) throw new Error("The selected parent directory does not exist.");
      const targetStats = await getStats(specification.projectPath);
      if (targetStats && !targetStats.isDirectory) throw new Error("The project path already exists as a file.");
      if (targetStats && (await listDirectory(specification.projectPath)).length) {
        throw new Error("The project directory must be empty.");
      }
      if (specification.initializeGit) {
        const result = await Neutralino.os.execCommand("git --version");
        if (Number(result?.exitCode) !== 0) throw new Error("Git initialization was selected, but Git is not available.");
      }
      for (const entry of prepared.files) {
        if (await getStats(joinPath(specification.projectPath, entry.path))) {
          throw new Error(`Creation would overwrite an existing path: ${entry.path}`);
        }
      }
      return { targetExisted: Boolean(targetStats) };
    }

    async function ensureDirectory(path, createdDirectories) {
      if (await getStats(path)) return;
      await Neutralino.filesystem.createDirectory(path);
      createdDirectories.push(path);
    }

    async function rollback(projectPath, createdFiles, createdDirectories, removeProjectRoot) {
      try {
        if (await getStats(joinPath(projectPath, ".git"))) await Neutralino.filesystem.remove(joinPath(projectPath, ".git"));
      } catch (_error) {}
      for (const path of createdFiles.slice().reverse()) {
        try { await Neutralino.filesystem.remove(path); } catch (_error) {}
      }
      for (const path of createdDirectories.slice().reverse()) {
        try { await Neutralino.filesystem.remove(path); } catch (_error) {}
      }
      if (removeProjectRoot) {
        try { await Neutralino.filesystem.remove(projectPath); } catch (_error) {}
      }
    }

    /**
     * Create one validated project and return its canonical open targets.
     * Side effects are limited to the selected empty project directory and optional `git init`.
     */
    async function create(specification, prepared) {
      const preflightResult = await preflight(specification, prepared);
      const createdFiles = [];
      const createdDirectories = [];
      try {
        if (!preflightResult.targetExisted) await Neutralino.filesystem.createDirectory(specification.projectPath);
        for (const relativeDirectory of prepared.directories) {
          const segments = relativeDirectory.split("/");
          let current = specification.projectPath;
          for (const segment of segments) {
            current = joinPath(current, segment);
            await ensureDirectory(current, createdDirectories);
          }
        }
        for (const entry of prepared.files) {
          const targetPath = joinPath(specification.projectPath, entry.path);
          if (entry.copyFrom) {
            const content = await Neutralino.filesystem.readBinaryFile(entry.copyFrom);
            await Neutralino.filesystem.writeBinaryFile(targetPath, content);
          } else {
            await Neutralino.filesystem.writeFile(targetPath, entry.content);
          }
          createdFiles.push(targetPath);
        }
        if (specification.initializeGit) {
          const result = await Neutralino.os.execCommand("git init", { cwd: specification.projectPath });
          if (Number(result?.exitCode) !== 0) throw new Error(result?.stdErr || "Git initialization failed.");
        }
        return {
          projectPath: specification.projectPath,
          entryFile: prepared.generated.entryFile,
          createdPaths: createdDirectories.concat(createdFiles)
        };
      } catch (error) {
        await rollback(specification.projectPath, createdFiles, createdDirectories, !preflightResult.targetExisted);
        throw error;
      }
    }

    const api = { create, prepare, preflight };
    app?.registerModule?.("projectScaffolder", api);
    return api;
  }

  global.registerMarkdownViewerProjectScaffolder = registerMarkdownViewerProjectScaffolder;
})(typeof window !== "undefined" ? window : globalThis);
